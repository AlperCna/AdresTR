using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace AdresTR.Eval;

/// <summary>Renders evaluation results as Markdown and JSON.</summary>
internal static class Report
{
    public static string Summary(EvalResult r) =>
        $"{r.System} on {r.Set} (n={r.Count}): exact {Pct(r.ExactMatch)} [{Pct(r.ExactMatchCi.Low)}–{Pct(r.ExactMatchCi.High)}], " +
        $"micro-F1 {Pct(r.MicroF1)}, macro-F1 {Pct(r.MacroF1)}, il {Pct(r.IlAccuracy)}, ilçe {Pct(r.IlceAccuracy)}, " +
        $"birim@1 {Pct(r.BirimAccuracy)}, @5 {Pct(r.BirimAt5)}, ECE {Num(r.Ece)}, {Num(r.MillisecondsPerAddress)} ms/address";

    public static string FieldTable(EvalResult r)
    {
        var sb = new StringBuilder();
        sb.AppendLine("| Field | P | R | F1 | Support |").AppendLine("|---|---:|---:|---:|---:|");
        foreach (var (field, s) in r.Fields)
        {
            sb.AppendLine(Invariant($"| {field} | {Pct(s.Precision)} | {Pct(s.Recall)} | {Pct(s.F1)} | {s.Support} |"));
        }

        return sb.ToString();
    }

    public static string Leaderboard(IReadOnlyList<EvalResult> results, string dataVersion)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Benchmark results").AppendLine();
        sb.AppendLine("Generated by `dotnet run --project tools/AdresTR.Eval -- report`. Do not edit by hand.");
        sb.AppendLine(Invariant($"Gazetteer {dataVersion}. Metrics and comparison rules: [../SCHEMA.md](../SCHEMA.md), [../README.md](../README.md)."));
        sb.AppendLine("Percentages; `[low–high]` = bootstrap 95% CI; `–` = not applicable (e.g. the system returns no ids or confidence).");
        sb.AppendLine("Speed is measured with BenchmarkDotNet (`benchmarks/`), not here, so this file is deterministic.").AppendLine();

        foreach (IGrouping<string, EvalResult> set in results.GroupBy(r => r.Set))
        {
            sb.AppendLine(Invariant($"## {set.Key} (n={set.First().Count})")).AppendLine();
            sb.AppendLine("| System | Exact match | Micro-F1 | Macro-F1 | il | ilçe | birim@1 | birim@5 | MRR | ECE |");
            sb.AppendLine("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|");
            foreach (EvalResult r in set)
            {
                sb.AppendLine(
                    $"| {r.System} | {Pct(r.ExactMatch)} [{Pct(r.ExactMatchCi.Low)}–{Pct(r.ExactMatchCi.High)}] | {Pct(r.MicroF1)} [{Pct(r.MicroF1Ci.Low)}–{Pct(r.MicroF1Ci.High)}] | {Pct(r.MacroF1)} " +
                    $"| {Pct(r.IlAccuracy)} | {Pct(r.IlceAccuracy)} | {Pct(r.BirimAccuracy)} | {Pct(r.BirimAt5)} | {Pct(r.BirimMrr)} " +
                    $"| {Num(r.Ece)} |");
            }

            sb.AppendLine().AppendLine("<details><summary>Per-field F1</summary>").AppendLine();
            string[] fields = [.. Labels.Scored.Where(f => set.Any(r => r.Fields.ContainsKey(f)))];
            sb.AppendLine("| System | " + string.Join(" | ", fields) + " |");
            sb.AppendLine("|---|" + string.Concat(fields.Select(_ => "---:|")));
            foreach (EvalResult r in set)
            {
                sb.AppendLine($"| {r.System} | " + string.Join(" | ", fields.Select(f => r.Fields.TryGetValue(f, out FieldScore? s) ? Pct(s.F1) : "–")) + " |");
            }

            sb.AppendLine().AppendLine("</details>").AppendLine();

            string[] tags = [.. set.SelectMany(r => r.ByTag.Keys).Distinct().Order(StringComparer.Ordinal)];
            if (tags.Length > 0)
            {
                sb.AppendLine("<details><summary>Exact match by tag / noise</summary>").AppendLine();
                sb.AppendLine("| Tag | n | " + string.Join(" | ", set.Select(r => r.System)) + " |");
                sb.AppendLine("|---|---:|" + string.Concat(set.Select(_ => "---:|")));
                foreach (string tag in tags)
                {
                    int n = set.Select(r => r.ByTag.TryGetValue(tag, out var v) ? v.N : 0).Max();
                    sb.AppendLine(Invariant($"| {tag} | {n} | ") + string.Join(" | ", set.Select(r => r.ByTag.TryGetValue(tag, out var v) ? Pct(v.ExactMatch) : "–")) + " |");
                }

                sb.AppendLine().AppendLine("</details>").AppendLine();
            }
        }

        return sb.ToString();
    }

    public static string Json(IReadOnlyList<EvalResult> results)
    {
        var array = new JsonArray();
        foreach (EvalResult r in results)
        {
            var fields = new JsonObject();
            foreach (var (name, s) in r.Fields)
            {
                fields[name] = new JsonObject
                {
                    ["precision"] = Round(s.Precision), ["recall"] = Round(s.Recall), ["f1"] = Round(s.F1), ["support"] = s.Support,
                };
            }

            array.Add(new JsonObject
            {
                ["system"] = r.System,
                ["set"] = r.Set,
                ["n"] = r.Count,
                ["exact_match"] = Round(r.ExactMatch),
                ["exact_match_ci"] = new JsonArray(Round(r.ExactMatchCi.Low), Round(r.ExactMatchCi.High)),
                ["micro_f1"] = Round(r.MicroF1),
                ["micro_f1_ci"] = new JsonArray(Round(r.MicroF1Ci.Low), Round(r.MicroF1Ci.High)),
                ["macro_f1"] = Round(r.MacroF1),
                ["il_accuracy"] = Round(r.IlAccuracy),
                ["ilce_accuracy"] = Round(r.IlceAccuracy),
                ["birim_accuracy"] = Round(r.BirimAccuracy),
                ["birim_accuracy_ci"] = new JsonArray(Round(r.BirimAccuracyCi.Low), Round(r.BirimAccuracyCi.High)),
                ["birim_at5"] = Round(r.BirimAt5),
                ["birim_mrr"] = Round(r.BirimMrr),
                ["ece"] = r.Ece is double e ? Round(e) : null,
                ["fields"] = fields,
            });
        }

        return array.ToJsonString(new JsonSerializerOptions(Jsonl.Options) { WriteIndented = true }) + "\n";

        static JsonNode? Round(double x) => double.IsNaN(x) ? null : JsonValue.Create(Math.Round(x, 4));
    }

    private static string Pct(double x) => double.IsNaN(x) ? "–" : (100 * x).ToString("F1", CultureInfo.InvariantCulture);

    private static string Num(double? x) => x is double v && !double.IsNaN(v) ? v.ToString("F3", CultureInfo.InvariantCulture) : "–";

    private static string Invariant(FormattableString s) => s.ToString(CultureInfo.InvariantCulture);
}

/// <summary>Consistency checks of eval examples against the gazetteer.</summary>
internal static class Validation
{
    public static IEnumerable<string> Check(EvalExample e, Gazetteer g)
    {
        if (string.IsNullOrWhiteSpace(e.License))
        {
            yield return "missing license";
        }

        foreach (Span s in e.Spans ?? [])
        {
            if (string.IsNullOrWhiteSpace(e.Text[s.Start..s.End]))
            {
                yield return $"span {s} covers only whitespace";
            }
        }

        Province? il = e.Il.Value is int plaka ? g.GetProvince(plaka) : null;
        District? ilce = e.Ilce.Value is int ilceId ? g.GetDistrict(ilceId) : null;
        SettlementUnit? birim = e.Birim.Value is int birimId ? g.GetUnit(birimId) : null;

        if (e.Il.Value is not null && il is null)
        {
            yield return $"unknown il {e.Il.Value}";
        }

        if (e.Ilce.Value is not null && ilce is null)
        {
            yield return $"unknown ilçe {e.Ilce.Value}";
        }

        if (e.Birim.Value is not null && birim is null)
        {
            yield return $"unknown birim {e.Birim.Value}";
        }

        if (birim is not null && ilce is not null && birim.District != ilce)
        {
            yield return $"birim {birim.Id} is not in ilçe {ilce.Id}";
        }

        if (ilce is not null && il is not null && ilce.Province != il)
        {
            yield return $"ilçe {ilce.Id} is not in il {il.Plaka}";
        }

        if (il is not null && e.Fields.GetValueOrDefault(Labels.Il) is string ilName && !Metrics.ValuesEqual(Labels.Il, il.Name, ilName))
        {
            yield return $"il field '{ilName}' ≠ gazetteer '{il.Name}'";
        }

        if (ilce is not null && e.Fields.GetValueOrDefault(Labels.Ilce) is string ilceName && !Metrics.ValuesEqual(Labels.Ilce, ilce.Name, ilceName))
        {
            yield return $"ilçe field '{ilceName}' ≠ gazetteer '{ilce.Name}'";
        }

        if (birim is not null && e.Fields.GetValueOrDefault(Labels.Mahalle) is string mahalle && !Metrics.ValuesEqual(Labels.Mahalle, birim.Name, mahalle))
        {
            yield return $"mahalle field '{mahalle}' ≠ gazetteer '{birim.Name}'";
        }

        if (e.Fields.GetValueOrDefault(Labels.CsbmTur) is string tur &&
            tur is not ("cadde" or "sokak" or "bulvar" or "meydan" or "kume_evler" or "cikmaz" or "yol"))
        {
            yield return $"invalid csbm_tur '{tur}'";
        }

        if (e.Fields.GetValueOrDefault(Labels.PostaKodu) is string pk && (pk.Length != 5 || !pk.All(char.IsAsciiDigit)))
        {
            yield return $"invalid posta_kodu '{pk}'";
        }
    }
}
