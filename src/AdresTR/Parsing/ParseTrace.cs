namespace AdresTR;

/// <summary>Options for <see cref="AddressParser.Parse(string, ParseOptions)"/>.</summary>
public sealed class ParseOptions
{
    /// <summary>Default options (no trace).</summary>
    public static readonly ParseOptions Default = new();

    /// <summary>
    /// Include a <see cref="ParseTrace"/> that explains how the result was reached: tokens, the number of hypotheses
    /// considered and the best alternative readings with their scores. Costs a little extra time and memory.
    /// </summary>
    public bool IncludeTrace { get; init; }
}

/// <summary>A token of the input as the parser saw it.</summary>
/// <param name="Text">The token as written.</param>
/// <param name="Start">Start offset in the input.</param>
/// <param name="End">End offset (exclusive) in the input.</param>
/// <param name="Folded">ASCII-folded matching form.</param>
/// <param name="Glued">The token was split off a glued word ("147sok" → "147" + "sok").</param>
public sealed record TraceToken(string Text, int Start, int End, string Folded, bool Glued);

/// <summary>A span of the input and the role an alternative assigns to it.</summary>
/// <param name="Role">"il", "ilce", "mahalle", "semt", "street", "site", "blok", "door", "floor", "flat", "postal", "landmark", "noise" or "ignored".</param>
/// <param name="Value">Normalized value.</param>
/// <param name="Text">The covered input text, including type words ("Caferağa Mah.").</param>
/// <param name="Start">Start offset in the input.</param>
/// <param name="End">End offset (exclusive) in the input.</param>
/// <param name="Local">Local plausibility of this reading of the span, in [0, 1].</param>
public sealed record TraceComponent(string Role, string Value, string Text, int Start, int End, double Local);

/// <summary>One alternative reading of the whole address.</summary>
/// <param name="Rank">1 = the reading the parser chose.</param>
/// <param name="Score">Total score (structure + administrative consistency).</param>
/// <param name="Probability">Share of the confidence mass of this distinct output.</param>
/// <param name="Components">The spans and their roles.</param>
/// <param name="Province">Resolved il, if any.</param>
/// <param name="District">Resolved ilçe, if any.</param>
/// <param name="Unit">Resolved mahalle/köy, if any.</param>
/// <param name="UnitCandidates">How many units the reading leaves possible (1 = determined).</param>
public sealed record TraceAlternative(
    int Rank, double Score, double Probability, IReadOnlyList<TraceComponent> Components,
    string? Province, string? District, string? Unit, int UnitCandidates);

/// <summary>How a <see cref="ParseResult"/> was reached.</summary>
/// <param name="Tokens">The input tokens.</param>
/// <param name="HypothesisCount">Span hypotheses generated by the classifier.</param>
/// <param name="Alternatives">Best distinct readings, best first.</param>
public sealed record ParseTrace(IReadOnlyList<TraceToken> Tokens, int HypothesisCount, IReadOnlyList<TraceAlternative> Alternatives);
